import Foundation
import SmartTubeIOSCore
import os

private let captionsLog = Logger(subsystem: appSubsystem, category: "ShortsCaptions")

/// Captions for the Shorts player. The embed can't show YouTube's own captions (its
/// controls are hidden), so this fetches the Short's caption tracks from `/player`
/// and renders the cues natively, driven by the embed's reported playback time.
@MainActor
@Observable
final class ShortsCaptionsController {

    /// The cue to show now, if any.
    var cueText: String? { captions.currentCaptionCue?.text }
    /// The track being shown; nil while off, loading, or when the Short has none.
    var activeTrack: CaptionTrack? { captions.selectedCaption }

    private let api: InnerTubeAPI
    private let captions = CaptionsManager()
    @ObservationIgnored private var videoId: String?
    @ObservationIgnored private var loadTask: Task<Void, Never>?

    init(api: InnerTubeAPI) {
        self.api = api
    }

    /// Shows captions for `videoId` when `enabled`; clears them otherwise.
    /// `preferredLanguage` wins when the Short has it, else the Short's own track.
    func apply(videoId: String?, enabled: Bool, preferredLanguage: String?, currentTime: TimeInterval) {
        guard enabled, let videoId else {
            stop()
            return
        }
        guard videoId != self.videoId else { return }
        stop()
        self.videoId = videoId
        loadTask = Task { [api] in
            do {
                let tracks = try await api.fetchCaptionTracks(videoId: videoId)
                guard !Task.isCancelled, self.videoId == videoId else { return }
                let track =
                    preferredLanguage.flatMap { CaptionTrack.matching($0, in: tracks) }
                    ?? tracks.first { !$0.isAutoGenerated } ?? tracks.first
                captionsLog.notice(
                    "\(videoId, privacy: .public): \(tracks.count, privacy: .public) tracks, showing \(track?.id ?? "none", privacy: .public)"
                )
                captions.selectCaption(track, currentTime: currentTime)
            } catch {
                captionsLog.notice(
                    "no caption tracks for \(videoId, privacy: .public): \(String(describing: error), privacy: .public)"
                )
            }
        }
    }

    func update(time: TimeInterval) {
        captions.updateCaptionCue(for: time)
    }

    private func stop() {
        loadTask?.cancel()
        loadTask = nil
        videoId = nil
        captions.reset()
    }
}
