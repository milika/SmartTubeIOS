import Foundation
import Testing

@testable import SmartTubeIOSCore

// MARK: - parseCaptionTracks
//
// Pure parsing coverage for `InnerTubeAPI.parseCaptionTracks(from:)`, the
// caption-only extractor used by the TOS player. It is split out of
// `parsePlayerInfo` because that method throws ("Stream URLs require
// decryption") for cipher-protected/SABR videos *after* parsing the caption
// tracks, which silently dropped captions for most videos.

@Suite("InnerTube caption track parsing")
struct InnerTubeCaptionTracksTests {

    private func playerJSON(captionTracks: [[String: Any]]) -> [String: Any] {
        [
            "captions": [
                "playerCaptionsTracklistRenderer": [
                    "captionTracks": captionTracks
                ]
            ]
        ]
    }

    @Test("parses manual and auto-generated tracks, resolving names and fmt=vtt")
    func parsesTracks() async {
        let json = playerJSON(captionTracks: [
            [
                "vssId": ".en",
                "languageCode": "en",
                "name": ["runs": [["text": "English"]]],
                "baseUrl": "https://www.youtube.com/api/timedtext?v=abc&fmt=srv3&lang=en",
            ],
            [
                "vssId": "a.de",
                "languageCode": "de-DE",
                "kind": "asr",
                "displayName": "Deutsch (automatisch erzeugt)",
                "baseUrl": "https://www.youtube.com/api/timedtext?v=abc&lang=de-DE",
            ],
        ])
        let api = InnerTubeAPI()
        let tracks = await api.parseCaptionTracks(from: json)

        #expect(tracks.count == 2)
        #expect(tracks[0].id == ".en")
        #expect(tracks[0].name == "English")
        #expect(tracks[0].languageCode == "en")
        #expect(tracks[0].isAutoGenerated == false)
        #expect(tracks[0].baseURL.absoluteString.contains("fmt=vtt"))

        #expect(tracks[1].id == "a.de")
        #expect(tracks[1].name == "Deutsch (automatisch erzeugt)")
        #expect(tracks[1].languageCode == "de-DE")
        #expect(tracks[1].isAutoGenerated == true)
    }

    @Test("accepts the TV embed shape where the URL is `url` not `baseUrl`")
    func parsesTVEmbedURLShape() async {
        let json = playerJSON(captionTracks: [
            [
                "vssId": ".en",
                "languageCode": "en",
                "languageName": "English",
                "url": "https://www.youtube.com/api/timedtext?v=abc&lang=en",
            ]
        ])
        let api = InnerTubeAPI()
        let tracks = await api.parseCaptionTracks(from: json)

        #expect(tracks.count == 1)
        #expect(tracks[0].name == "English")
        #expect(tracks[0].baseURL.absoluteString.contains("fmt=vtt"))
    }

    @Test("missing captions returns an empty list")
    func missingCaptions() async {
        let api = InnerTubeAPI()
        #expect(await api.parseCaptionTracks(from: [:]).isEmpty)
        #expect(
            await api.parseCaptionTracks(
                from: ["captions": ["playerCaptionsTracklistRenderer": [:] as [String: Any]]]
            ).isEmpty)
    }

    @Test("a track without a usable URL is dropped")
    func dropsTrackWithoutURL() async {
        let json = playerJSON(captionTracks: [["vssId": ".en", "languageCode": "en"]])
        let api = InnerTubeAPI()
        #expect(await api.parseCaptionTracks(from: json).isEmpty)
    }
}
